export const contractCommands: readonly CommandDefinition[] = [
  ...softwareCommands,
  ...officeCommands,
];
export const contractReads: readonly ReadDefinition[] = [...softwareReads, ...officeReads];
export const contractEvents: readonly EventDefinition[] = [...softwareEvents, ...officeEvents];

export function findCommand(name: string): CommandDefinition | undefined {
  return contractCommands.find((definition) => definition.name === name);
}

export function findRead(name: string): ReadDefinition | undefined {
  return contractReads.find((definition) => definition.name === name);
}

export function findEvent(type: string): EventDefinition | undefined {
  return contractEvents.find((definition) => definition.type === type);
}

export type CommandsDescribeResult = z.infer<typeof commandsDescribe.result>;

// The `commands.describe` result for a set of definitions, by default the whole contract.
// Provisional definitions are left out.
export function describeContract(
  commands: readonly CommandDefinition[] = contractCommands,
  reads: readonly ReadDefinition[] = contractReads,
): CommandsDescribeResult {
  return {
    commands: commands.flatMap((definition) => describeCommand(definition) ?? []),
    reads: reads.flatMap((definition) => describeRead(definition) ?? []),
  };
}

