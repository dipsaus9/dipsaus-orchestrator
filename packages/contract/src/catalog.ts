const DRAFT = "https://json-schema.org/draft/2020-12/schema";

function document(title: string, defs: Record<string, JsonSchema>): JsonSchema {
  return {
    $schema: DRAFT,
    title: `dipo contract: ${title}`,
    $comment: "Generated by `bun run contract:schema`. Do not edit by hand.",
    $defs: defs,
  };
}

// The JSON Schema export (0004), as file name to document. Pure: writing the files is the
// `contract:schema` script's job.
export function contractJsonSchemas(): Record<string, JsonSchema> {
  const shared: Record<string, JsonSchema> = {};
  for (const [name, schema] of Object.entries(sharedSchemas)) {
    shared[name] = jsonSchemaOf(schema);
  }

  const work: Record<string, JsonSchema> = {};
  for (const [name, schema] of Object.entries(workSchemas)) {
    work[name] = jsonSchemaOf(schema);
  }

  const commands: Record<string, JsonSchema> = {};
  for (const definition of contractCommands) {
    commands[`${definition.name}.args`] = jsonSchemaOf(definition.args);
    commands[`${definition.name}.result`] = jsonSchemaOf(definition.result);
  }

  const reads: Record<string, JsonSchema> = {};
  for (const definition of contractReads) {
    reads[`${definition.name}.args`] = jsonSchemaOf(definition.args);
    reads[`${definition.name}.result`] = jsonSchemaOf(definition.result);
  }

  const events: Record<string, JsonSchema> = {};
  for (const definition of contractEvents) {
    events[`${definition.type}.data`] = jsonSchemaOf(definition.data);
  }

  return {
    "shared.schema.json": document("ids, frames, envelopes and errors", shared),
    "work.schema.json": document("story and work model, views and the field block", work),
    "commands.schema.json": document("command args and results", commands),
    "reads.schema.json": document("read args and results", reads),
    "events.schema.json": document("event data", events),
    "config.schema.json": softwareConfigJsonSchema(),
  };
}
